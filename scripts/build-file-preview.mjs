import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { layout } from '../assets/layout.js';

const root = new URL('../', import.meta.url);
const output = new URL('assets/app.file.js', root);
const fileLayout = structuredClone(layout);
const lettering = fileLayout.sections
  .filter(scene => scene.type === 'collection')
  .flatMap(scene => scene.content.filter(item => item.type === 'text'));

// External file:// CSS masks are blocked by browsers. Embed just these small
// SVGs; images and the video keep their portable paths beside index.html.
await Promise.all(lettering.map(async item => {
  const svg = await readFile(new URL(item.src, root));
  item.src = `data:image/svg+xml;base64,${svg.toString('base64')}`;
}));

const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['app.js'],
  outfile: fileURLToPath(output),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  charset: 'utf8',
  write: false,
  banner: { js: '// Generated by npm run build. Edit app.js / lib / assets/layout.js, not this file.' },
  plugins: [{
    name: 'inline-file-preview-masks',
    setup(builder) {
      builder.onLoad({ filter: /[/\\]assets[/\\]layout\.js$/ }, () => ({
        contents: `export const layout = ${JSON.stringify(fileLayout)};`,
        loader: 'js',
      }));
    },
  }],
});

const bundle = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (bundle !== existing) throw new Error('file:// preview is out of date. Run npm run build.');
  console.log('file:// preview matches the current sources.');
} else {
  await writeFile(output, bundle);
  console.log(`Built assets/app.file.js (${lettering.length} embedded SVG masks).`);
}
